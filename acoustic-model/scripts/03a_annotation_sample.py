"""Stage 3.2: draw and export the blinded pause-annotation sample (PLAN.md 3.2).

Runs only after D1 is decided and the split exists, because the sample must come from the
training portion only. Writes blinded 60 s clips to data/annotation/, the key to a git-ignored
*.local.csv, and a committed summary that shows no per-clip class.
"""

import sys

import pandas as pd
import soundfile as sf

from mzazi_acoustic.common import config, guards
from mzazi_acoustic.feature_engineering import annotation_sample, pause_detector


def main():
    splits_file = config.PROCESSING_RESULTS / "splits.csv"
    if config.D1_DECISION is None or not splits_file.exists():
        sys.exit("Not yet: the annotation sample needs D1 decided and splits.csv made (training portion only).")
    out = config.FEATURE_RESULTS
    out.mkdir(parents=True, exist_ok=True)

    report = pd.read_csv(config.PROCESSING_RESULTS / "processing_report.csv")
    pool = report[report["role"] == "training_pool"]
    train = guards.load_rows(pool, pd.read_csv(splits_file))
    eligible = train[train["trimmed_s"] >= config.ANNOTATION_MIN_TRIMMED_SECONDS].copy()

    # The noise-guard flag comes from the detector itself, run on the same processed audio it will
    # be validated on, so "noisy" means "the part of the detector we most need to check is active".
    flags = []
    for row in eligible.itertuples():
        y, sr = sf.read(config.PROCESSED_DIR / f"{row.file_id}.wav", dtype="float32")
        dynamic_range = pause_detector.detect_pauses(y, sr).dynamic_range_db
        flags.append(dynamic_range < config.NOISE_GUARD_ACTIVE_BELOW_DB)
    eligible["noise_guard_active"] = flags
    # Stage 1 noise-floor estimate, for the fallback when too few clips trigger the noise guard.
    floors = pd.read_csv(config.COLLECTION_RESULTS / "file_manifest.csv")[["file_id", "noise_floor_dbfs"]]
    eligible = eligible.merge(floors, on="file_id", how="left")

    sample, shortfall = annotation_sample.draw_annotation_sample(eligible)
    key = annotation_sample.export_segments(sample, config.PROCESSED_DIR, config.DATA_DIR / "annotation")
    key.to_csv(out / "annotation_key.local.csv", index=False)

    def spread(values):
        return f"median {values.median():.1f} s, min {values.min():.1f}, max {values.max():.1f} (n = {len(values)})"

    lines = ["# Stage 3.2 - Pause-annotation sample", "",
             "Generated by `scripts/03a_annotation_sample.py`. Clips are blinded; the key is in "
             "`annotation_key.local.csv` and stays closed until annotation is done.", "",
             f"- Drawn from {len(eligible)} eligible training-portion clips (trimmed length at least "
             f"{config.ANNOTATION_MIN_TRIMMED_SECONDS:.0f} s), {config.ANNOTATION_FILES} clips, "
             f"{annotation_sample.PER_CLASS} per class, one per subject.",
             f"- Noise guard active: {int(sample['noise_guard_active'].sum())} of {len(sample)} sampled clips; "
             f"{int(eligible['noise_guard_active'].sum())} of {len(eligible)} eligible clips.",
             f"- Noisy clips per class ({config.ANNOTATION_NOISY_PER_CLASS} wanted each) that had to come from the "
             f"highest Stage 1 noise-floor fallback: {({config.LABEL_NAMES[k]: int(v) for k, v in shortfall.items()})}. "
             f"How each clip was picked: {sample['picked_as'].value_counts().to_dict()}.",
             "- Trimmed duration, sampled clips: " + spread(sample["trimmed_s"]),
             "- Trimmed duration, all training-portion pool clips: " + spread(train["trimmed_s"]),
             "  (Eligibility requires 70 s, so the sample favours longer clips; shown so the bias is visible.)", ""]
    (out / "annotation_sample.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
