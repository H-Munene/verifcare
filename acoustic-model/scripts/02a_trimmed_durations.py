"""Stage 2, first part: trimmed duration of every recording, and clip/subject counts per dataset definition.

Runs before the split exists: it needs no labels beyond the class column and fits nothing. It exists
so decisions D6/D7 can be made on counts *after* the pre-registered 30 s minimum. Processed audio
is not written yet; that happens in the full Stage 2 run once D1 and D7 are decided.
"""

import pandas as pd

from mzazi_acoustic.common import config, raw_data
from mzazi_acoustic.common.audio import read_mono
from mzazi_acoustic.data_processing import eligibility, standardise

OUT = config.PROCESSING_RESULTS


def measure_durations():
    manifest = pd.read_csv(config.COLLECTION_RESULTS / "file_manifest.csv")
    lookup = pd.read_csv(config.COLLECTION_RESULTS / "file_lookup.local.csv").set_index("file_id")["rel_path"]
    rows = []
    for i, row in enumerate(manifest.itertuples(), start=1):
        y, sr = read_mono(config.DATASET_DIR / lookup[row.file_id])
        y16 = standardise.to_16k_mono(y, sr)
        _, trimmed_seconds = standardise.trim_and_truncate(y16, config.TARGET_SAMPLE_RATE)
        rows.append({"file_id": row.file_id, "raw_s": round(row.duration_s, 3), "trimmed_s": round(trimmed_seconds, 3)})
        if i % 50 == 0:
            print(f"  {i}/{len(manifest)}")
    table = pd.DataFrame(rows)
    table["kept_s"] = table["trimmed_s"].clip(upper=config.MAX_DURATION_SECONDS)
    table["meets_minimum"] = table["trimmed_s"] >= config.MIN_DURATION_SECONDS
    return table


def markdown_counts(title, frame):
    counts = eligibility.count_by_class(frame, config.LABEL_NAMES)
    lines = [f"**{title}**", "", "| class | clips | subjects |", "|---|---|---|"]
    lines += [f"| {name} | {r.clips} | {r.subjects} |" for name, r in counts.iterrows()]
    return lines + [""]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    raw_data.verify()
    durations = measure_durations()
    ages = pd.read_csv(config.COLLECTION_RESULTS / "age_at_recording.csv")
    table = ages.merge(durations, on="file_id")
    table.to_csv(OUT / "trimmed_durations.csv", index=False)

    long_enough = table["meets_minimum"]
    primary = eligibility.primary_dataset(table)
    near_onset = eligibility.near_onset_only(table)
    over_70 = eligibility.over_70_sensitivity(table)

    lines = ["# Stage 2 (part 1) - Trimmed durations and dataset sizes", "",
             "Generated by `scripts/02a_trimmed_durations.py`. Trimming uses the pause detector's own speech boundaries; "
             f"the minimum is {config.MIN_DURATION_SECONDS:.0f} s after trimming, and kept audio is truncated to "
             f"{config.MAX_DURATION_SECONDS:.0f} s. No split, features or processed audio yet.", "",
             "## Effect of the 30 s minimum on all 455 recordings", "",
             *markdown_counts("Before the minimum", table),
             *markdown_counts("After the minimum", table[long_enough]),
             *markdown_counts("Excluded by the minimum", table[~long_enough]),
             "Subjects above are those with at least one excluded clip; a subject disappears entirely only if all of "
             f"their clips are excluded: dementia {table[table.label == 1].groupby('subject_id')['meets_minimum'].any().eq(False).sum()}, "
             f"no dementia {table[table.label == 0].groupby('subject_id')['meets_minimum'].any().eq(False).sum()}.", "",
             "## Dataset definitions, after the 30 s minimum", "",
             *markdown_counts("D6 option A (primary): both classes wholly 55+", table[primary & long_enough]),
             *markdown_counts("D7 (b): option A + dementia clips only after onset or 0-5 years before",
                              table[primary & near_onset & long_enough]),
             *markdown_counts("D6 option B (sensitivity subset, Stage 5.2 only): both classes wholly over 70",
                              table[over_70 & long_enough]),
             "## Trimmed duration by class (all recordings, seconds)", ""]
    for label, name in config.LABEL_NAMES.items():
        d = table.loc[table["label"] == label, "trimmed_s"]
        lines.append(f"- {name}: median {d.median():.1f}, Q1 {d.quantile(0.25):.1f}, Q3 {d.quantile(0.75):.1f}, "
                     f"min {d.min():.1f}, max {d.max():.1f}; median trimmed away {(table.loc[table.label == label, 'raw_s'] - d).median():.2f} s")
    (OUT / "dataset_sizes.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
