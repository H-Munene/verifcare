"""Decision D1: apply the pre-registered rule to the full listening audit (PLAN.md decisions table).

Needs session 1 complete. Session 2 (the hidden repeats) is scored for listener agreement when it
is complete, and reported as pending otherwise; the decision itself uses session 1 only. The rule
is mechanical and was written down before the listener heard anything, so the output is the
decision the developer then records in config.D1_DECISION.
"""

import sys

import pandas as pd

from mzazi_acoustic.common import config
from mzazi_acoustic.data_collection import listening_audit as la

OUT = config.COLLECTION_RESULTS
ALLOWED = {**{c: {"yes", "no"} for c in la.YES_NO_COLUMNS}, "background_noise": {"none", "mild", "strong"},
           "target_speech_share": {"<25%", "25-50%", "50-75%", ">75%"}}


def load_session(name):
    sheet = pd.read_csv(OUT / f"full_audit_{name}.csv", dtype=str)
    bad = [f"{r.audit_id}: {c}" for r in sheet.itertuples() for c, ok in ALLOWED.items()
           if str(getattr(r, c)).strip() not in ok]
    return sheet, bad


def counts_by_class(audited):
    rows = []
    for column in la.YES_NO_COLUMNS:
        rows.append({"answer": f"{column} = yes",
                     **{config.LABEL_NAMES[lab]: int((audited.loc[audited.label == lab, column] == "yes").sum())
                        for lab in (1, 0)}})
    return pd.DataFrame(rows)


def main():
    session1, problems = load_session("session1")
    if problems:
        sys.exit(f"Session 1 isn't complete ({len(problems)} missing or unexpected answers), e.g. {problems[:5]}")
    key = pd.read_csv(OUT / "full_audit_key.local.csv")
    audited = session1.merge(key[key.session == 1], on="audit_id", validate="one_to_one")
    # overlapping speech implies another voice; the sheets must agree before the rule is applied
    contradictions = audited[(audited.overlapping_speech == "yes") & (audited.other_voices == "no")]
    if len(contradictions):
        sys.exit(f"Contradictory answers (overlap yes, other voices no): {list(contradictions.audit_id)}; please fix.")

    people = la.people_with_other_voices(audited)
    result = la.d1_decision(people, config.D1_FISHER_ALPHA, config.D1_RATE_GAP, config.D1_MIN_DEMENTIA_PEOPLE)
    pd.DataFrame([result]).to_csv(OUT / "d1_decision.csv", index=False)

    session2, problems2 = load_session("session2")
    if problems2:
        agreement_lines = [f"- Session 2 (hidden repeats) not complete yet: agreement pending."]
    else:
        repeats = session2.merge(key[key.session == 2][["audit_id", "file_id"]], on="audit_id")
        pairs = audited.merge(repeats, on="file_id", suffixes=("", "_second"))
        first = pairs[la.YES_NO_COLUMNS]
        second = pairs[[f"{c}_second" for c in la.YES_NO_COLUMNS]].set_axis(la.YES_NO_COLUMNS, axis=1)
        table = la.agreement(first, second)
        table.to_csv(OUT / "full_audit_agreement.csv", index=False)
        agreement_lines = [f"- {row.column}: {row.percent_agreement} % agreement, kappa {row.cohens_kappa} "
                           f"({row.n_clips} clips)" for row in table.itertuples()]

    counts = counts_by_class(audited)
    lines = ["# Decision D1 - Full listening audit", "",
             "Generated by `scripts/01f_full_audit_decision.py`. The rule was pre-registered (PLAN.md, decisions table) "
             "before the listener heard any clip.", "",
             f"- Clips audited: {len(audited)} ({int((audited.role == 'training_pool').sum())} pool, "
             f"{int((audited.role == 'trajectory').sum())} trajectory).",
             f"- Pool people with another voice in any clip: dementia {result['rate_dementia']:.1%}, "
             f"controls {result['rate_control']:.1%} (gap {result['gap']:+.1%}; Fisher p = {result['fisher_p']:.3f}).",
             f"- Differs clearly (p < {config.D1_FISHER_ALPHA} or gap > {config.D1_RATE_GAP:.0%}): {result['differs_clearly']}.",
             f"- Dementia people left under (c): {result['dementia_people_left_under_c']} "
             f"(minimum {config.D1_MIN_DEMENTIA_PEOPLE}; viable: {result['c_viable']}).",
             f"- **Decision by the pre-registered rule: ({result['decision']})**: {result['reason']}.", "",
             "## Answers by class (clips)", "", "| answer | dementia | no_dementia |", "|---|---|---|",
             *[f"| {r.answer} | {r.dementia} | {r.no_dementia} |" for r in counts.itertuples()], "",
             "## Listener agreement (session 2 repeats vs session 1)", "", *agreement_lines, ""]
    (OUT / "full_audit_summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
