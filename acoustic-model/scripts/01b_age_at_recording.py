"""Stage 1, decision D6: age at recording by class, from DementiaNet's metadata and the clip suffixes.

Writes (committed, anonymised): results/01_data_collection/age_at_recording.csv,
control_suffix_order_evidence.csv and age_summary.md. The metadata sheet itself holds real names,
so it is downloaded to data/ (git-ignored).
"""

import urllib.request

import numpy as np
import pandas as pd

from mzazi_acoustic.common import config
from mzazi_acoustic.data_collection import age_metadata

OUT = config.COLLECTION_RESULTS


def load_sheet(name):
    path = config.METADATA_FILES[name]
    if not path.exists():
        url = (f"https://docs.google.com/spreadsheets/d/{config.METADATA_SHEET_ID}/export"
               f"?format=csv&gid={config.METADATA_TABS[name]}")
        urllib.request.urlretrieve(url, path)
    sheet = pd.read_csv(path)
    keys = sheet["name"].map(age_metadata.normalise_name)
    if keys.duplicated().any():
        raise ValueError(f"{name} sheet lists a person twice; resolve by hand before continuing")
    return sheet


def load_files():
    manifest = pd.read_csv(OUT / "file_manifest.csv")[["file_id", "subject_id", "label"]]
    lookup = pd.read_csv(OUT / "file_lookup.local.csv")
    parts = lookup["rel_path"].str.split("/")
    lookup["person_folder"], lookup["filename"] = parts.str[1], parts.str[-1]
    return manifest.merge(lookup[["file_id", "person_folder", "filename"]], on="file_id")


def band_table(ages, by):
    """Counts per class and age band, for files or for subjects (a subject counted once per band)."""
    data = ages if by == "files" else ages.drop_duplicates(["subject_id", "age_band"])
    table = pd.crosstab(data["label"].map(config.LABEL_NAMES), data["age_band"])
    order = [b for b in ["<55", "55-70", ">70", "straddles", "unknown"] if b in table.columns]
    return table[order]


def to_markdown(table):
    header = "| class | " + " | ".join(table.columns) + " |"
    lines = [header, "|" + "---|" * (len(table.columns) + 1)]
    for index, row in table.iterrows():
        lines.append(f"| {index} | " + " | ".join(str(v) for v in row) + " |")
    return lines


def main():
    files = load_files()
    dementia_sheet, control_sheet = load_sheet("dementia"), load_sheet("no_dementia")

    evidence = age_metadata.control_suffix_order_evidence(files, control_sheet)
    evidence.to_csv(OUT / "control_suffix_order_evidence.csv", index=False)

    ages, last_year = age_metadata.ages_for_files(files, dementia_sheet, control_sheet)
    ages = ages.merge(files[["file_id", "subject_id"]], on="file_id")
    ages = ages[["file_id", "subject_id", "label", "bucket", "in_metadata", "age_low", "age_high", "age_band"]]
    ages.to_csv(OUT / "age_at_recording.csv", index=False)

    dementia = ages[ages["label"] == 1]
    bounded = dementia.dropna(subset=["age_low", "age_high"])
    midpoint = (bounded["age_low"] + bounded["age_high"]) / 2
    controls = ages[ages["label"] == 0]
    best = evidence.iloc[0]

    lines = ["# Stage 1 - Age at recording (decision D6)", "",
             "Generated by `scripts/01b_age_at_recording.py` from DementiaNet's metadata sheet and the clip-name suffixes. "
             "DementiaNet records no recording dates, so every age is a range.", "",
             "## How the clip suffix maps to time", "",
             "- Dementia `_0/_5/_10/_15`: after symptom onset; 0-5, 5-10, 10-15 years before onset (sheet columns "
             "'URLs after symptoms', '5 years', '5 < 10 years', '10 < 15 years').",
             f"- No dementia `_1/_2/_3`: {best.suffix_1} / {best.suffix_2} / {best.suffix_3}. Established from the data: "
             f"of {best.people_checked} controls in the sheet, this ordering matches the URL columns exactly for "
             f"{best.exact_match} and as a subset for {best.subset_match}; the next-best ordering matches "
             f"{evidence.iloc[1].exact_match} exactly (`control_suffix_order_evidence.csv`). "
             "The README describes these buckets two inconsistent ways (5/10/15 years before death or current age, "
             "and >70 / 55-70 / <55), and the sheet's column headers are the age bands.",
             f"- Clip suffixes seen: dementia {dementia['bucket'].value_counts(dropna=False).to_dict()}, "
             f"no dementia {controls['bucket'].value_counts(dropna=False).to_dict()}.", "",
             "## Coverage", "",
             f"- Dementia: {dementia['subject_id'].nunique()} subjects, {dementia.drop_duplicates('subject_id')['in_metadata'].sum()} in the sheet; "
             f"{len(bounded)} of {len(dementia)} clips have a bounded age (unbounded = missing onset year or an unknown suffix).",
             f"- No dementia: {controls['subject_id'].nunique()} subjects, only {controls.drop_duplicates('subject_id')['in_metadata'].sum()} in the sheet. "
             "The age band still follows from the suffix for every control clip, assuming the suffix convention "
             "confirmed on the sheet's controls holds for the rest (same naming scheme, same dataset).",
             f"- Upper bounds for living people use {last_year}, the latest death year in the sheet (the dataset has no date).", "",
             "## Age band at recording, by class", "",
             "A dementia clip gets a band only if its whole age range falls inside it; 'straddles' means it crosses 55 or 70.", "",
             "Clips:", "", *to_markdown(band_table(ages, "files")), "",
             "Subjects (a subject is counted in every band they have a clip in):", "", *to_markdown(band_table(ages, "subjects")), "",
             f"Dementia clips with a bounded age, midpoint of the range: median {np.median(midpoint):.0f}, "
             f"Q1 {np.percentile(midpoint, 25):.0f}, Q3 {np.percentile(midpoint, 75):.0f}, "
             f"min {midpoint.min():.0f}, max {midpoint.max():.0f} (n = {len(midpoint)}).", ""]
    (OUT / "age_summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
