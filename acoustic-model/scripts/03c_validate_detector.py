"""Stage 3.2: score the pause detector against the developer's hand-marked pauses (PLAN.md 3.2).

Runs only once the annotation key and every ann_XX.txt label track exist. The detector runs on the
whole processed clip, as in deployment; only pauses inside the annotated segment are scored.
Results are per clip and pooled per condition (counts summed first, then precision/recall).
The committed output carries no class labels, so looking at it can't turn into tuning by class.
"""

import sys
import zlib

import numpy as np
import pandas as pd
import soundfile as sf

from mzazi_acoustic.common import config
from mzazi_acoustic.feature_engineering import pause_validation

COUNT_COLUMNS = ["n_detected", "n_annotated", "n_matched",
                 "short_n_detected", "short_detected_matched", "short_n_annotated", "short_annotated_matched",
                 "long_n_detected", "long_detected_matched", "long_n_annotated", "long_annotated_matched",
                 "n_annotated_below_minimum"]


def pooled(per_clip):
    totals = per_clip.groupby("condition", sort=False)[COUNT_COLUMNS].sum()
    totals["precision"] = totals["n_matched"] / totals["n_detected"]
    totals["recall"] = totals["n_matched"] / totals["n_annotated"]
    for band in pause_validation.BANDS:
        totals[f"{band}_precision"] = totals[f"{band}_detected_matched"] / totals[f"{band}_n_detected"]
        totals[f"{band}_recall"] = totals[f"{band}_annotated_matched"] / totals[f"{band}_n_annotated"]
    return totals.reset_index().assign(ann_id="pooled")


def main():
    key_file = config.FEATURE_RESULTS / "annotation_key.local.csv"
    label_dir = config.DATA_DIR / "annotation"
    if not key_file.exists():
        sys.exit("Not yet: no annotation sample (run scripts/03a_annotation_sample.py first).")
    key = pd.read_csv(key_file)
    missing = [a for a in key["ann_id"] if not (label_dir / f"{a}.txt").exists()]
    if missing:
        sys.exit(f"Not yet: label tracks missing for {missing}.")

    rows = []
    for row in key.itertuples():
        y, sr = sf.read(config.PROCESSED_DIR / f"{row.file_id}.wav", dtype="float32")
        # Label times are relative to the 60 s clip; shift them onto the full recording.
        marks = [(s + row.segment_start_s, e + row.segment_start_s)
                 for s, e in pause_validation.read_audacity_labels(label_dir / f"{row.ann_id}.txt")]
        # Stable per-file offset, so each clip's noise is reproducible and differs between clips.
        rng = np.random.default_rng(config.SEED + zlib.crc32(row.file_id.encode()))
        for result in pause_validation.score_recording(y, sr, marks, row.segment_start_s, row.segment_end_s, rng):
            rows.append({"ann_id": row.ann_id, "noise_guard_active": row.noise_guard_active, **result})
    per_clip = pd.DataFrame(rows)
    table = pd.concat([per_clip, pooled(per_clip)], ignore_index=True)
    table.to_csv(config.FEATURE_RESULTS / "pause_detector_validation.csv", index=False)

    summary = pooled(per_clip).set_index("condition")
    lines = ["# Stage 3.2 - Pause-detector agreement with hand-marked pauses", "",
             f"Generated by `scripts/03c_validate_detector.py`; {len(key)} clips, 60 s each, "
             f"match tolerance {config.BOUNDARY_TOLERANCE_SECONDS * 1000:.0f} ms at both ends. "
             "Pooled over clips (counts summed, then precision/recall).", "",
             "| condition | precision | recall | short P | short R | long P | long R |", "|---|---|---|---|---|---|---|"]
    for condition, r in summary.iterrows():
        lines.append(f"| {condition} | {r.precision:.3f} | {r.recall:.3f} | {r.short_precision:.3f} | "
                     f"{r.short_recall:.3f} | {r.long_precision:.3f} | {r.long_recall:.3f} |")
    (config.FEATURE_RESULTS / "pause_detector_validation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
