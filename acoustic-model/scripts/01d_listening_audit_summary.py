"""Stage 1 step 10: summarise the developer's blinded listening audit by class, for decision D1.

Run only after all rows are filled in: it joins the answers to the local key (which the listener
kept closed until then). It writes a per-class summary; per-clip answers stay in the committed
sheet (audit ids only), and the key stays local.
"""

import sys

import pandas as pd

from mzazi_acoustic.common import config

OUT = config.COLLECTION_RESULTS
YES_NO = ["other_voices", "overlapping_speech", "music", "laughter", "applause"]
ALLOWED = {**{c: {"yes", "no"} for c in YES_NO}, "background_noise": {"none", "mild", "strong"},
           "target_speech_share": {"<25%", "25-50%", "50-75%", ">75%"}}


def main():
    answers = pd.read_csv(OUT / "listening_audit.csv", dtype=str)
    problems = [f"{row.audit_id}: {col} = {getattr(row, col)!r}" for row in answers.itertuples()
                for col, allowed in ALLOWED.items() if str(getattr(row, col)).strip() not in allowed]
    if problems:
        sys.exit("The audit sheet isn't complete or has unexpected values:\n" + "\n".join(problems))

    key = pd.read_csv(OUT / "listening_audit_key.local.csv")
    audit = answers.merge(key, on="audit_id", validate="one_to_one")
    report = pd.read_csv(config.PROCESSING_RESULTS / "processing_report.csv")[["file_id", "role"]]
    audit = audit.merge(report, on="file_id", how="left")
    audit["class"] = audit["label"].map(config.LABEL_NAMES)

    # Answers that contradict each other are flagged for the listener, never corrected here.
    inconsistent = audit[(audit["overlapping_speech"] == "yes") & (audit["other_voices"] == "no")]

    lines = ["# Stage 1 - Listening audit summary (decision D1)", "",
             "Generated by `scripts/01d_listening_audit_summary.py` from the developer's blinded answers "
             "(`listening_audit.csv`) joined to the local key after the audit was complete.", "",
             f"{len(audit)} clips, 10 per class, one per person, drawn from all 455 recordings before any Stage 2 "
             f"exclusion. {int((audit['role'] == 'training_pool').sum())} of them are in the current training pool.", "",
             "## Counts by class", "",
             "| answer | " + " | ".join(sorted(audit["class"].unique())) + " |", "|---|---|---|"]
    for column in YES_NO:
        counts = audit[audit[column] == "yes"].groupby("class").size()
        lines.append(f"| {column} = yes | " + " | ".join(str(counts.get(c, 0)) for c in sorted(audit["class"].unique())) + " |")
    for column in ["background_noise", "target_speech_share"]:
        for value in sorted(audit[column].unique()):
            counts = audit[audit[column] == value].groupby("class").size()
            lines.append(f"| {column} = {value} | " + " | ".join(str(counts.get(c, 0)) for c in sorted(audit["class"].unique())) + " |")
    lines += ["", "## Same counts, training-pool clips only", ""]
    pool = audit[audit["role"] == "training_pool"]
    for column in ["other_voices", "overlapping_speech"]:
        counts = pool[pool[column] == "yes"].groupby("class").size()
        totals = pool.groupby("class").size()
        lines.append(f"- {column} = yes: " + ", ".join(f"{c} {counts.get(c, 0)}/{totals.get(c, 0)}" for c in sorted(totals.index)))
    lines += ["", "## For the listener to check", ""]
    if inconsistent.empty:
        lines.append("- No contradictory answers.")
    for row in inconsistent.itertuples():
        lines.append(f"- {row.audit_id}: overlapping speech = yes but other voices = no. Overlap normally needs a second "
                     "voice; please confirm (e.g. was it someone else's laughter over the speaker?).")
    (OUT / "listening_audit_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
