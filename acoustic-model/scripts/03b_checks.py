"""Stage 3.3 - checks before any modelling, on the training portion only (PLAN.md 3.3).

Refuses to run until the developer has signed off the pause detector (config.DETECTOR_SIGNED_OFF)
and the feature matrix exists, so no check ever sees features from an unvalidated detector.
Writes the checks and a proposed final feature list for the Checkpoint 3 sign-off. It never
writes config.py: freezing the list is the developer's decision.
"""

import sys
import zlib

import numpy as np
import pandas as pd
import soundfile as sf

from mzazi_acoustic.common import config, degradation, guards
from mzazi_acoustic.feature_engineering import checks

OUT = config.FEATURE_RESULTS
MATRIX = OUT / "feature_matrix.csv"


def degraded_family_a(train):
    """Re-extract family A for every training clip under each degradation condition.

    Noise is seeded per file from the global seed and the file_id, so re-running gives identical
    noise, and different files never share a noise sample.
    """
    from mzazi_acoustic.feature_engineering.features import extract_features

    by_condition = {name: [] for name, _, _ in degradation.conditions()}
    for i, row in enumerate(train.itertuples(), start=1):
        y, sr = sf.read(config.PROCESSED_DIR / f"{row.file_id}.wav", dtype="float32")
        rng = np.random.default_rng([config.SEED, zlib.crc32(row.file_id.encode())])
        for name, noise_type, snr in degradation.conditions():
            degraded, _ = degradation.degrade(y, sr, noise_type, snr, rng)
            values = extract_features(degraded.astype(np.float32), sr)
            by_condition[name].append({"file_id": row.file_id, **{f: values[f] for f in config.FAMILY_A_FEATURES}})
        if i % 25 == 0:
            print(f"  degraded {i}/{len(train)}")
    return {name: pd.DataFrame(rows) for name, rows in by_condition.items()}


def main():
    if not config.DETECTOR_SIGNED_OFF:
        sys.exit("The pause detector is not signed off (config.DETECTOR_SIGNED_OFF is False): no checks yet.")
    if not MATRIX.exists():
        sys.exit(f"{MATRIX} doesn't exist yet: run scripts/03_features.py first.")

    features = config.MODEL_FEATURES
    train = guards.load_rows(pd.read_csv(MATRIX))
    report = pd.read_csv(config.PROCESSING_RESULTS / "processing_report.csv")[["file_id", "age_band", "trimmed_s"]]
    proxies = pd.read_csv(config.COLLECTION_RESULTS / "file_manifest.csv")[["file_id", *checks.PROXIES]]
    train = train.drop(columns=[c for c in ["age_band", "trimmed_s"] if c in train]).merge(report, on="file_id")
    train = train.merge(proxies, on="file_id")

    completeness = checks.completeness(train, features)
    kept, redundant = checks.redundancy(train, features)
    kept, dependency, vif = checks.dependency(train, kept)
    confound = checks.channel_confound(train, features)
    shift = checks.degradation_shift(train, degraded_family_a(train), config.FAMILY_A_FEATURES)
    benchmark, level = checks.within_person_benchmark(train, config.FAMILY_A_FEATURES)
    flags = checks.degradation_flags(shift, benchmark)
    duration = checks.duration_dependence(train, features)
    differences = checks.class_differences(train, features)
    direction = checks.direction_check(differences)
    final = checks.final_feature_list(redundant, dependency, confound)

    OUT.mkdir(parents=True, exist_ok=True)
    completeness.to_csv(OUT / "completeness.csv", index=False)
    redundant.to_csv(OUT / "redundancy.csv", index=False)
    dependency.merge(vif, on="feature", how="left").to_csv(OUT / "dependency_check.csv", index=False)
    confound.to_csv(OUT / "channel_confound.csv", index=False)
    shift.to_csv(OUT / "degradation_shift.csv", index=False)
    flags.assign(benchmark_level=level).to_csv(OUT / "degradation_flags.csv", index=False)
    duration.to_csv(OUT / "duration_dependence.csv", index=False)
    differences.to_csv(OUT / "class_differences.csv", index=False)
    direction.to_csv(OUT / "direction_check.csv", index=False)
    final.to_csv(OUT / "final_feature_list.csv", index=False)

    stopping = completeness.loc[completeness["stop"], "feature"].tolist()
    stop_note = ([f"**STOP (PLAN.md 3.3 step 1): median fills are common (> {config.FILL_RATE_STOP:.0%}) or differ "
                  f"by class (> {config.FILL_CLASS_GAP_STOP:.0%} points) for {stopping}. Report to the developer "
                  "before any modelling.**", ""] if stopping else [])
    lines = ["# Stage 3.3 - Checks before modelling (training portion only)", "",
             "Generated by `scripts/03b_checks.py`. Every number is in the CSV named beside it.", "",
             *stop_note,
             f"- Training rows: {len(train)} clips, {train['subject_id'].nunique()} people.",
             f"- Completeness (`completeness.csv`): {int((completeness['n_nan'] + completeness['n_inf']).gt(0).sum())} "
             "features need median fills (structural values are already set); fills per class are in the CSV.",
             f"- Redundancy (`redundancy.csv`): {len(redundant)} dropped at |r| >= {config.REDUNDANCY_ABS_R}.",
             f"- Dependency (`dependency_check.csv`): rank {int(dependency['rank_before'].iloc[0])} of "
             f"{int(dependency['n_features_before'].iloc[0])}; {int((~dependency['kept']).sum())} dropped; "
             f"{int(vif['above_report_threshold'].sum())} with VIF > {config.VIF_REPORT_THRESHOLD:g} (reported only).",
             f"- Channel confound (`channel_confound.csv`): family B removals: "
             f"{sorted(confound.loc[confound['remove'], 'feature'].unique()) or 'none'}.",
             f"- Degradation (`degradation_flags.csv`): benchmark level {level}; flagged into 5.1: "
             f"{sorted(flags.loc[flags['flagged'], 'feature']) or 'none'}.",
             f"- Duration dependence (`duration_dependence.csv`): flagged into 5.1: "
             f"{sorted(duration.loc[duration['flagged'], 'feature']) or 'none'}.",
             f"- Direction check (`direction_check.csv`): {int(direction['agrees'].sum())} of {len(direction)} "
             "agree with the literature (descriptive, never forced).", "",
             "## Proposed final feature list (for the developer's Checkpoint 3 sign-off)", ""]
    for row in final.itertuples():
        lines.append(f"- {'keep' if row.kept else 'DROP'} `{row.feature}`" + (f": {row.reason}" if row.reason else ""))
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
