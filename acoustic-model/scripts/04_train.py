"""Stage 4 - Model training: 5 x 5 nested CV, comparison, selection, final fit (PLAN.md Stage 4).

Refuses to run until Stages 2-3 have produced the split, the folds, the feature matrix and the
frozen final feature list. Loads training rows only, through the test-set guard.
"""

import sys

import pandas as pd

from mzazi_acoustic.common import config, guards
from mzazi_acoustic.model_training import compare, cv, final

OUT = config.TRAINING_RESULTS
REQUIRED = [
    config.PROCESSING_RESULTS / "splits.csv",
    config.PROCESSING_RESULTS / "cv_folds.csv",
    config.FEATURE_RESULTS / "feature_matrix.csv",
    config.FEATURE_RESULTS / "final_feature_list.csv",
]


def kept_features(final_list):
    """Only the features the Stage 3.3 rules kept: the list also records the removed ones, with reasons."""
    return final_list.loc[final_list["kept"].astype(bool), "feature"].tolist()


def main():
    missing = [p.name for p in REQUIRED if not p.exists()]
    if missing:
        sys.exit(f"Stage 4 can't run yet; missing: {', '.join(missing)}")
    OUT.mkdir(parents=True, exist_ok=True)

    feature_cols = kept_features(pd.read_csv(config.FEATURE_RESULTS / "final_feature_list.csv"))
    matrix = pd.read_csv(config.FEATURE_RESULTS / "feature_matrix.csv")
    training = guards.load_rows(matrix)  # training rows only
    folds = pd.read_csv(config.PROCESSING_RESULTS / "cv_folds.csv")
    splits = pd.read_csv(guards.SPLITS_FILE)
    trajectory_ids = splits.loc[splits["role"] == "trajectory", "file_id"]
    trajectory = matrix[matrix["file_id"].isin(trajectory_ids)]

    results = cv.run_cv(training, folds, feature_cols, trajectory=trajectory)
    fold_metrics = results["fold_metrics"]
    fold_metrics.to_csv(OUT / "fold_metrics.csv", index=False)
    results["oof_predictions"].to_csv(OUT / "oof_predictions.csv", index=False)
    results["tuning_log"].to_csv(OUT / "tuning_log.csv", index=False)
    if results["trajectory_predictions"] is not None:
        results["trajectory_predictions"].to_csv(OUT / "trajectory_oof_predictions.csv", index=False)

    tuned = fold_metrics[fold_metrics["variant"] == "tuned"]
    n_test = tuned["n_val"].mean()
    n_train = tuned["n_train"].mean()
    chosen, record, tables = compare.select(tuned, n_train, n_test)
    pd.concat(tables, ignore_index=True).to_csv(OUT / "comparisons.csv", index=False)

    model, final_log = final.fit_final(training, feature_cols, chosen)
    pd.DataFrame(final_log).to_csv(OUT / "final_tuning_log.csv", index=False)
    final.save(model, final.build_metadata(chosen, feature_cols, model))

    summary = tuned.groupby("model")[["roc_auc_person", "brier_person", "ece_person", "roc_auc_clip"]].agg(["mean", "std"])
    lines = ["# Stage 4 - Model selection", "",
             "Generated by `scripts/04_train.py`. 5 repeats x 5 subject-grouped folds; tuned, calibrated candidates. "
             "Person-weighted metrics are primary; per-clip (unweighted) metrics are alongside in fold_metrics.csv.", "",
             "Mean (SD) across the 25 folds:", "", "```", summary.round(4).to_string(), "```", "",
             "## Selection (pre-registered cascade, compare.py)", "", *[f"- {r}" for r in record], "",
             f"**Chosen: {chosen}.** Refit on the whole training portion and saved to models/. "
             "Its refit search score is a selection score only, not a performance estimate.", ""]
    (OUT / "selection.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
