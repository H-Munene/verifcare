"""Stage 1 - Data collection: measure exactly what data exists (PLAN.md Stage 1).

Committed outputs (results/01_data_collection/) contain no real names or name-bearing paths.
Anything with a name goes to a *.local.csv file, which is git-ignored.
"""

import numpy as np
import pandas as pd

from mzazi_acoustic.common import config, raw_data, stats
from mzazi_acoustic.common.audio import read_mono
from mzazi_acoustic.data_collection import channel_quality, inventory, listening_audit, subjects

OUT = config.COLLECTION_RESULTS
PROXIES = ["noise_floor_dbfs", "bandwidth_hz", "noise_flatness"]


def build_file_table():
    print("Verifying raw data against the Stage 0 freeze...")
    hashes = raw_data.verify()
    prefix = config.DATASET_DIR.relative_to(config.RAW_DIR).as_posix() + "/"
    hashes["rel_path"] = hashes["rel_path"].str.removeprefix(prefix)

    files = inventory.discover(config.DATASET_DIR)
    files = files.merge(hashes[["rel_path", "sha256"]], on="rel_path", how="left")
    files["label"] = files["class_folder"].map(config.FOLDER_TO_LABEL)

    # Subject identity from the person folder name.
    salt = subjects.load_or_create_salt()
    files["normalised_name"] = files["person_folder"].fillna("").map(subjects.normalise_name)
    files["subject_id"] = files["normalised_name"].map(lambda n: subjects.make_subject_id(n, salt))
    files["filename_name"] = files["filename"].map(subjects.name_in_filename)
    files["filename_matches_folder"] = files["filename_name"] == files["normalised_name"]

    files = files.sort_values(["subject_id", "rel_path"]).reset_index(drop=True)
    files["file_id"] = files["subject_id"] + "_f" + (files.groupby("subject_id").cumcount() + 1).map("{:02d}".format)
    return files


def measure_files(files):
    rows = []
    for i, row in enumerate(files.itertuples(), start=1):
        path = config.DATASET_DIR / row.rel_path
        facts = inventory.file_facts(path)
        if facts["opens"] and facts["n_frames"] > 0:
            y, sr = read_mono(path)
            facts.update(channel_quality.channel_proxies(y, sr))
        rows.append(facts)
        if i % 50 == 0:
            print(f"  measured {i}/{len(files)} files")
    return pd.concat([files, pd.DataFrame(rows)], axis=1)


def subject_table(files):
    grouped = files.groupby("subject_id")
    table = pd.DataFrame({
        "label": grouped["label"].first(),
        "n_labels": grouped["label"].nunique(),
        "class_folders": grouped["class_folder"].agg(lambda s: ";".join(sorted(set(s)))),
        "n_files": grouped.size(),
        "total_duration_s": grouped["duration_s"].sum().round(2),
        "median_file_duration_s": grouped["duration_s"].median().round(2),
    }).reset_index()
    return table


def confound_check(files, subject_ids_with_label):
    """Each channel proxy vs class label, aggregated per subject first (PLAN.md Stage 1 step 9)."""
    per_subject = files.dropna(subset=PROXIES).groupby("subject_id")[PROXIES].mean()
    per_subject = per_subject.join(subject_ids_with_label.set_index("subject_id")["label"])
    rows = []
    for proxy in PROXIES:
        r, p_r = stats.point_biserial(per_subject[proxy], per_subject["label"])
        u, p_u, rbc = stats.mann_whitney(per_subject.loc[per_subject["label"] == 1, proxy],
                                         per_subject.loc[per_subject["label"] == 0, proxy])
        rows.append({
            "proxy": proxy,
            "median_dementia": per_subject.loc[per_subject["label"] == 1, proxy].median(),
            "median_no_dementia": per_subject.loc[per_subject["label"] == 0, proxy].median(),
            "point_biserial_r": r, "point_biserial_p": p_r,
            "mann_whitney_u": u, "mann_whitney_p": p_u, "rank_biserial": rbc,
        })
    table = pd.DataFrame(rows)
    # Bonferroni across the proxies, separately for each test (m = number of proxies).
    table["point_biserial_p_bonferroni"] = stats.bonferroni(table["point_biserial_p"])
    table["mann_whitney_p_bonferroni"] = stats.bonferroni(table["mann_whitney_p"])
    return table.round(4), len(per_subject)


def describe(values):
    values = pd.Series(values).dropna()
    q = values.quantile([0, 0.25, 0.5, 0.75, 1]).round(1).tolist()
    return f"n={len(values)}, min {q[0]}, Q1 {q[1]}, median {q[2]}, Q3 {q[3]}, max {q[4]}, mean {values.mean():.1f}"


def write_summary(files, subject_tab, name_pairs, confound, n_confound_subjects, audit_sample):
    readable = files[files["opens"] & (files["n_frames"] > 0)]
    dup_groups = files[files.duplicated("sha256", keep=False)].groupby("sha256")
    lines = ["# Stage 1 - Data collection summary", "",
             "Generated by `scripts/01_collect.py`. Every number below comes from the CSV files in this folder.", ""]

    lines += ["## Structure as found", ""]
    for folder, group in files.groupby("class_folder"):
        lines.append(f"- `{folder}`: {group['person_folder'].nunique()} person folders, {len(group)} files, "
                     f"proposed label {config.FOLDER_TO_LABEL.get(folder, 'UNMAPPED')}")
    lines.append(f"- Files outside the `<class>/<person>/<file>` layout: {int((~files['layout_ok']).sum())}")
    lines.append(f"- File extensions: {files['filename'].str.rsplit('.', n=1).str[-1].str.lower().value_counts().to_dict()}")
    multi_folder = subject_tab[subject_tab["class_folders"].str.contains(";")]
    lines.append(f"- Subjects found in more than one class folder: {len(multi_folder)} "
                 f"(folder combinations: {multi_folder['class_folders'].value_counts().to_dict()})")
    lines.append(f"- Subjects whose folders map to conflicting labels: {int((subject_tab['n_labels'] > 1).sum())}")
    lines.append("")

    lines += ["## Subject identity", "",
              f"- Unique subjects after name normalisation: {len(subject_tab)}",
              f"- Near-duplicate name pairs flagged for manual review (not merged): {len(name_pairs)}",
              f"- Files whose file name doesn't match their person folder: {int((~files['filename_matches_folder']).sum())}",
              "- Details with names are in `name_review.local.csv` (local only).", ""]

    lines += ["## Per-file facts", "",
              f"- Containers: {files['container'].value_counts(dropna=False).to_dict()}",
              f"- Codecs: {files['codec'].value_counts(dropna=False).to_dict()}",
              f"- Sample rates (Hz): {files['sample_rate'].value_counts(dropna=False).sort_index().to_dict()}",
              f"- Channels: {files['channels'].value_counts(dropna=False).to_dict()}",
              f"- Bit depths: {files['bit_depth'].value_counts(dropna=False).to_dict()}", ""]

    lines += ["## Integrity", "",
              f"- Files that don't open: {int((~files['opens']).sum())}",
              f"- Zero-length files (0 bytes or 0 samples): {int(((files['size_bytes'] == 0) | (files['n_frames'] == 0)).sum())}",
              f"- Exact duplicates (same SHA-256): {dup_groups.ngroups} groups covering {int(files.duplicated('sha256', keep=False).sum())} files"]
    for sha, group in dup_groups:
        lines.append(f"  - {sha[:12]}: files {', '.join(group['file_id'])}; subjects {', '.join(sorted(set(group['subject_id'])))}; "
                     f"labels {sorted(set(group['label']))}")
    lines.append("")

    lines += ["## Counts and class balance", ""]
    for label, name in config.LABEL_NAMES.items():
        subs = subject_tab[subject_tab["label"] == label]
        recs = readable[readable["label"] == label]
        lines.append(f"- {name}: {len(subs)} subjects, {len(recs)} readable recordings; recordings per subject "
                     f"min {subs['n_files'].min()}, mean {subs['n_files'].mean():.2f}, max {subs['n_files'].max()}")
    lines.append(f"- Overall recordings per subject: min {subject_tab['n_files'].min()}, "
                 f"mean {subject_tab['n_files'].mean():.2f}, max {subject_tab['n_files'].max()}")
    subj_share = (subject_tab["label"] == 1).mean()
    rec_share = (readable["label"] == 1).mean()
    lines.append(f"- Share of dementia: {subj_share:.1%} of subjects, {rec_share:.1%} of recordings")
    lines.append("")

    lines += ["## Recording duration per class (raw, before trimming)", ""]
    for label, name in config.LABEL_NAMES.items():
        recs = readable[readable["label"] == label]
        subs = subject_tab[subject_tab["label"] == label]
        below = recs["duration_s"] < config.MIN_DURATION_SECONDS
        lines.append(f"- {name}, per recording (s): {describe(recs['duration_s'])}")
        lines.append(f"- {name}, total per subject (s): {describe(subs['total_duration_s'])}")
        lines.append(f"- {name}: {int(below.sum())} recordings already under the {config.MIN_DURATION_SECONDS:.0f} s "
                     f"minimum before trimming (a lower bound on Stage 2 exclusions)")
    lines.append("")

    lines += ["## Channel-quality confound check", "",
              f"Proxies averaged per subject first ({n_confound_subjects} subjects), then tested against the label. "
              "Bonferroni across the 3 proxies, separately for each test. Rank-biserial > 0 means higher in the dementia group.", "",
              "| proxy | median dementia | median no dementia | point-biserial r | p (Bonf.) | rank-biserial | MWU p (Bonf.) |",
              "|---|---|---|---|---|---|---|"]
    for row in confound.itertuples():
        lines.append(f"| {row.proxy} | {row.median_dementia} | {row.median_no_dementia} | {row.point_biserial_r} | "
                     f"{row.point_biserial_p_bonferroni} | {row.rank_biserial} | {row.mann_whitney_p_bonferroni} |")
    lines += ["",
              "Caveat: the noise floor and noise flatness are measured on each file's quietest frames, which are mostly pauses, "
              "so they are partly coupled to how much the speaker pauses (PLAN.md 3.3).", ""]

    lines += ["## Listening audit", "",
              f"{len(audit_sample)} recordings ({config.LISTENING_AUDIT_PER_CLASS} per class, one per subject, shuffled) "
              f"were copied to `data/listening_audit/` under neutral names. Fill in `listening_audit.csv`; "
              "the key is in `listening_audit_key.local.csv` and should stay closed until the audit is done.", ""]

    (OUT / "summary.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    files = build_file_table()
    print(f"Found {len(files)} files. Measuring format facts and channel proxies...")
    files = measure_files(files)

    subject_tab = subject_table(files)
    name_pairs = subjects.near_duplicate_pairs(files["normalised_name"])

    # Local-only lookups (contain real names).
    folder_names = files.groupby("subject_id")["person_folder"].agg(lambda s: ";".join(sorted(set(s))))
    folder_names.rename("person_folders").reset_index().to_csv(OUT / "subject_id_lookup.local.csv", index=False)
    files[["file_id", "rel_path"]].to_csv(OUT / "file_lookup.local.csv", index=False)
    review = [{"issue": "near_duplicate_name", "name_a": a, "name_b": b, "similarity": r} for a, b, r in name_pairs]
    review += [{"issue": "filename_differs_from_folder", "name_a": row.normalised_name, "name_b": row.filename_name,
                "file_id": row.file_id} for row in files[~files["filename_matches_folder"]].itertuples()]
    pd.DataFrame(review, columns=["issue", "name_a", "name_b", "similarity", "file_id"]).to_csv(
        OUT / "name_review.local.csv", index=False)

    # Committed, anonymised outputs.
    manifest_cols = ["file_id", "subject_id", "label", "class_folder", "container", "codec", "sample_rate", "channels",
                     "bit_depth", "n_frames", "duration_s", "size_bytes", "sha256", "opens", "error",
                     "filename_matches_folder", *PROXIES]
    files[manifest_cols].round(4).to_csv(OUT / "file_manifest.csv", index=False)
    subject_tab.to_csv(OUT / "subject_manifest.csv", index=False)
    confound, n_confound_subjects = confound_check(files, subject_tab)
    confound.to_csv(OUT / "channel_confound.csv", index=False)

    readable = files[files["opens"] & (files["n_frames"] > 0)]
    audit_sample = listening_audit.draw_sample(readable, config.LISTENING_AUDIT_PER_CLASS, config.SEED)
    source_paths = {row.file_id: config.DATASET_DIR / row.rel_path for row in readable.itertuples()}
    listening_audit.export(audit_sample, source_paths, config.LISTENING_AUDIT_DIR)
    audit_sample.to_csv(OUT / "listening_audit_key.local.csv", index=False)
    template_path = OUT / "listening_audit.csv"
    if template_path.exists():
        print(f"Kept the existing {template_path.name} (it may already hold the listener's answers).")
    else:
        listening_audit.blank_template(audit_sample).to_csv(template_path, index=False)

    write_summary(files, subject_tab, name_pairs, confound, n_confound_subjects, audit_sample)
    print(f"Done. See {OUT / 'summary.md'}")


if __name__ == "__main__":
    main()
