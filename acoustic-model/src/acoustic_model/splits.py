"""Phase 2 subject-level train_pool/test split.

Carves out a locked test set now, never touched again until the final
locked evaluation (see the 12-phase list in acoustic-model-dev-log.md);
the remaining train_pool subjects are what later phases cross-validate
over (subject-aware/grouped CV substitutes for a separate fixed
validation split, so no third split is created here).

The split is subject-level and stratified by class label: no subject's
files ever cross a split boundary, and both splits preserve the
overall class balance. Only runs over subjects with at least one
preprocessed, included file (see preprocessing.py) - a subject with
zero included files can't be evaluated and is marked "excluded" here
rather than being silently dropped from the record.

Run via `scripts/run_splits.py`, not this module directly.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from sklearn.model_selection import train_test_split

from acoustic_model.config import (
    PREPROCESSING_RESULTS_DIR,
    RANDOM_SEED,
    SPLITS_RESULTS_DIR,
    TEST_SET_FRACTION,
)

EXCLUDED_SPLIT = "excluded"
TRAIN_POOL_SPLIT = "train_pool"
TEST_SPLIT = "test"


def _load_duration_report() -> pd.DataFrame:
    path = PREPROCESSING_RESULTS_DIR / "duration_report.csv"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found - run scripts/run_preprocessing.py before scripts/run_splits.py.")
    return pd.read_csv(path)


def build_subject_usability(duration_report: pd.DataFrame) -> pd.DataFrame:
    grouped = duration_report.groupby("subject_id")
    rows = []
    for subject_id, group in grouped:
        class_labels = group["class_label"].unique()
        included_count = int(group["included"].sum())
        rows.append(
            {
                "subject_id": subject_id,
                "class_label": class_labels[0] if len(class_labels) == 1 else "CONFLICT",
                "file_count_total": len(group),
                "file_count_included": included_count,
                "usable": included_count > 0,
            }
        )
    return pd.DataFrame(rows).sort_values("subject_id")


def assign_splits(
    subject_df: pd.DataFrame,
    random_seed: int = RANDOM_SEED,
    test_fraction: float = TEST_SET_FRACTION,
) -> pd.DataFrame:
    """Stratified subject-level split. subject_df needs subject_id, class_label, usable."""
    usable_df = subject_df[subject_df["usable"]].copy()
    excluded_df = subject_df[~subject_df["usable"]].copy()

    train_ids, test_ids = train_test_split(
        usable_df["subject_id"],
        test_size=test_fraction,
        random_state=random_seed,
        stratify=usable_df["class_label"],
    )
    test_id_set = set(test_ids)

    usable_df["split"] = usable_df["subject_id"].apply(
        lambda subject_id: TEST_SPLIT if subject_id in test_id_set else TRAIN_POOL_SPLIT
    )
    excluded_df["split"] = EXCLUDED_SPLIT

    return pd.concat([usable_df, excluded_df], ignore_index=True).sort_values("subject_id")


def _write_summary(path: Path, split_df: pd.DataFrame) -> None:
    lines: list[str] = []
    lines.append("# Subject Split Summary")
    lines.append("")
    lines.append("Generated by `scripts/run_splits.py`.")
    lines.append("Subject-level, stratified by class_label. No subject's files ever cross a split boundary.")
    lines.append("")

    lines.append("## Split sizes")
    lines.append("")
    for split_name in (TRAIN_POOL_SPLIT, TEST_SPLIT, EXCLUDED_SPLIT):
        group = split_df[split_df["split"] == split_name]
        if len(group) == 0:
            lines.append(f"{split_name}: 0 subjects.")
            continue
        counts = group["class_label"].value_counts()
        breakdown = ", ".join(f"{label}={counts.get(label, 0)}" for label in sorted(counts.index))
        lines.append(f"{split_name}: {len(group)} subjects ({breakdown}).")
    lines.append("")

    excluded = split_df[split_df["split"] == EXCLUDED_SPLIT]
    if len(excluded) > 0:
        lines.append("## Excluded subjects")
        lines.append("")
        lines.append("Subjects with zero included files after preprocessing (see preprocessing_summary.md), by subject_id only:")
        lines.append(", ".join(excluded["subject_id"].tolist()) + ".")
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def run() -> pd.DataFrame:
    SPLITS_RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    duration_report = _load_duration_report()
    subject_df = build_subject_usability(duration_report)
    split_df = assign_splits(subject_df)

    split_df.to_csv(SPLITS_RESULTS_DIR / "subject_splits.csv", index=False)
    _write_summary(SPLITS_RESULTS_DIR / "splits_summary.md", split_df)
    return split_df
