"""Phase 2 preprocessing: leading/trailing silence trim + resample to a
fixed target rate/channel count, applied per file with no fitting on
data (so this step introduces no leakage risk by construction - unlike
scaling/imputation/feature selection, which must be fit train-only,
trimming and resampling are deterministic, file-local transforms).

Also makes the file-inclusion decision deferred from the Phase 1
audit: `subj_063_f01` (and any other file) is included or excluded
based on its *actual measured post-trim duration* against
config.MIN_USABLE_DURATION_SECONDS, not its raw format alone.

Run via `scripts/run_preprocessing.py`, not this module directly.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import librosa
import pandas as pd
import soundfile as sf

from acoustic_model import dataset
from acoustic_model.config import (
    MIN_USABLE_DURATION_SECONDS,
    PREPROCESSING_RESULTS_DIR,
    PROCESSED_DATA_ROOT,
    SILENCE_TRIM_TOP_DB,
    TARGET_SAMPLE_RATE_HZ,
)

_UNREADABLE_EXCLUSION_REASON = "unreadable"
_TOO_SHORT_EXCLUSION_REASON = "post_trim_duration_below_threshold"


@dataclass
class ProcessedFileResult:
    raw_duration_seconds: float | None
    post_trim_duration_seconds: float | None
    silence_trimmed_seconds: float | None
    native_sample_rate_hz: int | None
    included: bool
    exclusion_reason: str | None
    error: str | None


def process_file(source_path: Path, output_path: Path) -> ProcessedFileResult:
    """Trim silence and resample one file, writing the result to output_path.

    output_path is only written when the file is included; excluded files leave
    no processed-audio artifact, so a later phase can rely on "file exists under
    PROCESSED_DATA_ROOT" as a cheap included-or-not check without re-reading
    duration_report.csv.
    """
    try:
        native_waveform, native_sample_rate_hz = librosa.load(
            str(source_path), sr=None, mono=True
        )
    except Exception as exc:
        return ProcessedFileResult(
            raw_duration_seconds=None,
            post_trim_duration_seconds=None,
            silence_trimmed_seconds=None,
            native_sample_rate_hz=None,
            included=False,
            exclusion_reason=_UNREADABLE_EXCLUSION_REASON,
            error=str(exc),
        )

    raw_duration_seconds = len(native_waveform) / native_sample_rate_hz

    trimmed_waveform, _ = librosa.effects.trim(
        native_waveform, top_db=SILENCE_TRIM_TOP_DB
    )
    post_trim_duration_seconds = len(trimmed_waveform) / native_sample_rate_hz
    silence_trimmed_seconds = raw_duration_seconds - post_trim_duration_seconds

    included = post_trim_duration_seconds >= MIN_USABLE_DURATION_SECONDS
    if not included:
        return ProcessedFileResult(
            raw_duration_seconds=raw_duration_seconds,
            post_trim_duration_seconds=post_trim_duration_seconds,
            silence_trimmed_seconds=silence_trimmed_seconds,
            native_sample_rate_hz=native_sample_rate_hz,
            included=False,
            exclusion_reason=_TOO_SHORT_EXCLUSION_REASON,
            error=None,
        )

    if native_sample_rate_hz != TARGET_SAMPLE_RATE_HZ:
        resampled_waveform = librosa.resample(
            trimmed_waveform,
            orig_sr=native_sample_rate_hz,
            target_sr=TARGET_SAMPLE_RATE_HZ,
        )
    else:
        resampled_waveform = trimmed_waveform

    output_path.parent.mkdir(parents=True, exist_ok=True)
    sf.write(
        str(output_path), resampled_waveform, TARGET_SAMPLE_RATE_HZ, subtype="PCM_16"
    )

    return ProcessedFileResult(
        raw_duration_seconds=raw_duration_seconds,
        post_trim_duration_seconds=post_trim_duration_seconds,
        silence_trimmed_seconds=silence_trimmed_seconds,
        native_sample_rate_hz=native_sample_rate_hz,
        included=True,
        exclusion_reason=None,
        error=None,
    )


def _write_summary(path: Path, report_df: pd.DataFrame) -> None:
    lines: list[str] = []
    lines.append("# Preprocessing Summary")
    lines.append("")
    lines.append("Generated by `scripts/run_preprocessing.py`.")
    lines.append(
        f"Silence trim threshold: {SILENCE_TRIM_TOP_DB}dB below peak (leading/trailing only)."
    )
    lines.append(f"Resample target: {TARGET_SAMPLE_RATE_HZ}Hz mono.")
    lines.append(f"Minimum usable post-trim duration: {MIN_USABLE_DURATION_SECONDS}s.")
    lines.append("")

    lines.append("## Inclusion")
    lines.append("")
    included_count = int(report_df["included"].sum())
    excluded_df = report_df[~report_df["included"]]
    lines.append(f"{included_count} of {len(report_df)} files included.")
    if len(excluded_df) > 0:
        lines.append(f"{len(excluded_df)} files excluded:")
        for reason, group in excluded_df.groupby("exclusion_reason"):
            lines.append(
                f"  - {reason}: {len(group)} file(s) - "
                + ", ".join(group["file_id"].tolist())
                + "."
            )
    else:
        lines.append("No files excluded.")
    lines.append("")

    if "subj_063_f01" in report_df["file_id"].values:
        row = report_df[report_df["file_id"] == "subj_063_f01"].iloc[0]
        lines.append("## subj_063_f01 resolution (deferred from Phase 1 audit)")
        lines.append("")
        lines.append(
            "Flagged in Phase 1 for a non-conforming raw format (mono, 16kHz, float subtype), but not excluded on that basis alone."
        )
        lines.append(
            f"Actual measured post-trim duration: {row['post_trim_duration_seconds']:.2f}s "
            f"(raw duration {row['raw_duration_seconds']:.2f}s, threshold {MIN_USABLE_DURATION_SECONDS}s)."
        )
        verdict = (
            "included" if row["included"] else f"excluded ({row['exclusion_reason']})"
        )
        lines.append(
            f"Resolution: {verdict}, decided from this measured duration, not from the format mismatch."
        )
        lines.append("")

    lines.append("## Silence trimmed")
    lines.append("")
    trimmed = report_df["silence_trimmed_seconds"].dropna()
    if len(trimmed) > 0:
        lines.append(
            f"Mean {trimmed.mean():.2f}s, median {trimmed.median():.2f}s, "
            f"max {trimmed.max():.2f}s trimmed per file across {len(trimmed)} readable files."
        )
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def run() -> pd.DataFrame:
    PREPROCESSING_RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    PROCESSED_DATA_ROOT.mkdir(parents=True, exist_ok=True)

    entries = dataset.build_file_index()

    rows = []
    for entry in entries:
        output_path = PROCESSED_DATA_ROOT / entry.subject_id / f"{entry.file_id}.wav"
        result = process_file(entry.path, output_path)
        rows.append(
            {
                "file_id": entry.file_id,
                "subject_id": entry.subject_id,
                "class_label": entry.class_label,
                "raw_duration_seconds": result.raw_duration_seconds,
                "post_trim_duration_seconds": result.post_trim_duration_seconds,
                "silence_trimmed_seconds": result.silence_trimmed_seconds,
                "native_sample_rate_hz": result.native_sample_rate_hz,
                "included": result.included,
                "exclusion_reason": result.exclusion_reason,
                "error": result.error,
            }
        )

    report_df = pd.DataFrame(rows)
    report_df.to_csv(PREPROCESSING_RESULTS_DIR / "duration_report.csv", index=False)
    _write_summary(PREPROCESSING_RESULTS_DIR / "preprocessing_summary.md", report_df)
    return report_df
